const dictionaries = { en, fr } as const;

if (process.env.NODE_ENV !== 'production') {
  const missing = (Object.keys(en) as TranslationKey[]).filter((key) => !(key in fr));
  if (missing.length) {
    // eslint-disable-next-line no-console
    console.warn('[i18n] Missing French translations for:', missing);
  }
}

export function useTranslation() {
  const { language, setLanguage } = useLanguage();

  const t = useCallback(
    (key: TranslationKey, params?: Record<string, string | number>): string => {
      const raw = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
      if (!params) return raw;
      return raw.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
    },
    [language],
  );

  return { t, language, setLanguage };
}

/** Exact English backend error strings that have a matching dictionary key. */
const ERROR_MESSAGE_KEYS: Record<string, TranslationKey> = Object.fromEntries(
  (Object.keys(en) as TranslationKey[])
    .filter((key) => key.startsWith('error.'))
    .map((key) => [en[key], key]),
) as Record<string, TranslationKey>;
ERROR_MESSAGE_KEYS['Patient not found'] = 'error.patientNotFound';
ERROR_MESSAGE_KEYS["This reset link is invalid."] = 'error.resetLinkInvalid';

/**
 * Translates a raw error string from the API (always English — the backend
 * has no locale awareness) into the current UI language. Messages without a
 * known mapping pass through unchanged rather than disappearing.
 */
export function translateError(message: string | undefined | null, t: (key: TranslationKey) => string): string {
  if (!message) return '';
  const key = ERROR_MESSAGE_KEYS[message];
  return key ? t(key) : message;
}
